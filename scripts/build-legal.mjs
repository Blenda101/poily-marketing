// Regenerates src/content/legal.ts from the owner-approved markdown in
// Apps/handoffs/admin_mkt/legal/ (the canonical source). Strips the
// "Publish at / Status" header line only; text is otherwise verbatim.
// Usage: node scripts/build-legal.mjs <legal-dir> <path-to-marked.esm.js>
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const [dir, markedPath] = process.argv.slice(2)
const { marked } = await import(pathToFileURL(markedPath).href)
const docs = {
  privacy: 'POILY_PRIVACY_POLICY.md',
  terms: 'POILY_TERMS_OF_SERVICE.md',
  dataDeletion: 'POILY_DATA_DELETION.md',
}
const out = {}
for (const [key, file] of Object.entries(docs)) {
  const lines = readFileSync(join(dir, file), 'utf8').split(/\r?\n/)
  const title = lines[0].replace(/^#\s+/, '')
  const body = lines.slice(1).filter((l) => !l.startsWith('**Publish at:**')).join('\n')
  out[key] = { title, html: marked.parse(body, { gfm: true }) }
}
writeFileSync(
  'src/content/legal.ts',
  '// GENERATED by scripts/build-legal.mjs — do not edit by hand.\n' +
    '// Source: Apps/handoffs/admin_mkt/legal/*.md (owner-approved 2026-11-17).\n' +
    `export const LEGAL = ${JSON.stringify(out, null, 2)} as const\n`,
)
console.log('wrote', Object.keys(out))
